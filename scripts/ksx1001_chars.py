def get_unicode_points():
    """Return U+xxxx format string for pyftsubset"""
    points = set()
    # ASCII printable
    for c in range(0x20, 0x7F):
        points.add(c)
    # General punctuation
    for c in range(0x2000, 0x2070):
        points.add(c)
    # CJK symbols
    for c in range(0x3000, 0x3040):
        points.add(c)
    # Hangul jamo
    for c in range(0x3131, 0x3164):
        points.add(c)
    # KS X 1001 chars
    for ch in KSX1001:
        if ch in (' ', ',', '\n'):
            continue
        points.add(ord(ch))
    # Fullwidth forms
    for c in range(0xFF01, 0xFF61):
        points.add(c)
    return ",".join(f"U+{p:04X}" for p in sorted(points))

if __name__ == "__main__":
    print(f"Total unique codepoints: {len(get_unicode_points().split(','))}")
    print(get_unicode_points()[:200] + "...")
